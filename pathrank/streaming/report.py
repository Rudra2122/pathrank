"""results/streaming/*.json -> results/RESULTS_streaming.md, and the table between the README markers."""
from __future__ import annotations

import json
import re
from pathlib import Path

START, END = "<!-- streaming-results:start -->", "<!-- streaming-results:end -->"


def _load(d: Path, name: str) -> dict | None:
    p = d / name
    return json.loads(p.read_text()) if p.exists() else None


def _n(x, unit: str = "") -> str:
    if x is None:
        return "not run"
    if isinstance(x, float) and not x.is_integer():
        return f"{x:,.2f}{unit}"
    return f"{int(x):,}{unit}"


def table(d: Path) -> str:
    prod, st, dry = _load(d, "producer.json"), _load(d, "stream.json"), _load(d, "producer_dryrun.json")
    bp, sp = _load(d, "batch_parity.json"), _load(d, "stream_parity.json")
    rows = []
    if prod:
        rows.append(("Producer throughput (Java, max rate)",
                     f"**{_n(prod['events_per_sec'])} events/s** ({prod['mb_per_sec']:.1f} MB/s), "
                     f"{_n(prod['acked'])} events, {prod['partitions']} partitions, acks={prod['acks']}, "
                     f"idempotence={str(prod['idempotence']).lower()}, {prod['errors']} send errors"
                     + (f"; Parquet read + serialize alone: {_n(dry['events_per_sec'])} events/s" if dry else "")))
    else:
        rows.append(("Producer throughput (Java, max rate)", "not run"))
    if st and st.get("source") != "kafka":
        rows.append(("End-to-end lag, Kafka -> S3 (p50 / p95)",
                     f"n/a: file source, no Kafka ({_n(st['events'])} events in {st['batches']} micro-batches)"))
    elif st and st.get("lag_ms"):
        lag = st["lag_ms"]
        rate = f" at a {_n(st.get('producer_rate'))} events/s replay" if st.get("producer_rate") else ""
        rows.append(("End-to-end lag, Kafka -> S3 (p50 / p95)",
                     f"**{_n(lag['p50'])} ms / {_n(lag['p95'])} ms** (p99 {_n(lag['p99'])} ms){rate}, "
                     f"trigger {st['trigger']}, {_n(st['events'])} events in {st['batches']} micro-batches"))
    else:
        rows.append(("End-to-end lag, Kafka -> S3 (p50 / p95)", "not run"))
    if bp:
        pd_s = bp["pandas_s"]
        rows.append(("Spark batch vs pandas, same features + data",
                     f"**Spark {bp['spark_s']:.1f} s vs pandas {pd_s['total_s']:.1f} s** "
                     f"({bp['speedup']}x; {_n(bp['pairs'])} user-job pairs, "
                     f"Spark {bp['spark']['master']} on {bp['machine']['cpus']} cores)"))
        rows.append(("Feature parity, Spark vs pandas `AsOf`",
                     f"**max diff {bp['max_abs_diff']:g}** over job_pop_all, job_pop_7d, user_n_apps, "
                     f"user_last ({_n(bp['users'])} users, {_n(bp['jobs'])} jobs, cutoff {bp['cutoff']}); "
                     f"{'PASS' if bp['pass'] else 'FAIL'}"))
    else:
        rows += [("Spark batch vs pandas, same features + data", "not run"),
                 ("Feature parity, Spark vs pandas `AsOf`", "not run")]
    if sp:
        jp, ua, br = sp["job_popularity"], sp["user_activity"], sp.get("bronze", {})
        rows.append(("Stream vs batch windows (1 h)",
                     f"max diff {sp['max_abs_diff']}; {_n(jp['matched'])} job windows + {_n(ua['matched'])} "
                     f"user windows matched; {jp['missing_closed'] + ua['missing_closed']} closed windows missing; "
                     f"{'PASS' if sp['pass'] else 'FAIL'}"))
        rows.append(("Kafka -> S3 completeness",
                     f"{_n(br.get('rows'))} rows landed / {_n(sp.get('producer_acked', sp['events_in_parquet']))} "
                     f"produced, {br.get('duplicates', '?')} duplicates"))
    lines = ["| Metric | Result |", "|---|---|"] + [f"| {a} | {b} |" for a, b in rows]
    return "\n".join(lines)


def write(results_dir: str = "results/streaming", readme: str = "README.md",
          out_md: str = "results/RESULTS_streaming.md", title: str = "PathRank streaming path: results",
          note: str = "") -> str:
    d = Path(results_dir)
    t = table(d)
    parts = [f"# {title}", "", note or f"Generated by `make stream-report` from `{results_dir}/*.json`.", "", t, ""]
    for name in ("producer.json", "producer_dryrun.json", "producer_lag.json", "stream.json", "batch_parity.json", "stream_parity.json"):
        j = _load(d, name)
        if j is not None:
            j = {k: v for k, v in j.items() if k != "per_batch"}
            parts += [f"## {name}", "", "```json", json.dumps(j, indent=1), "```", ""]
    Path(out_md).parent.mkdir(parents=True, exist_ok=True)
    Path(out_md).write_text("\n".join(parts))
    rp = Path(readme)
    if rp.exists():
        txt = rp.read_text()
        if START in txt and END in txt:
            txt = re.sub(re.escape(START) + r".*?" + re.escape(END), f"{START}\n{t}\n{END}", txt, flags=re.S)
            rp.write_text(txt)
    return t
