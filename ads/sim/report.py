"""results/ads/*.json + Redis freshness samples -> results/RESULTS_ads.md (and prints it)."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np


def freshness(host: str, port: int) -> dict | None:
    try:
        import redis
        r = redis.Redis(host=host, port=port, socket_timeout=3)
        vals = np.array([int(x) for x in r.lrange("ads:freshness_ms", 0, -1)])
        late = int(r.get("ads:late_events") or 0)
        bad = int(r.get("ads:malformed_events") or 0)
        dup = int(r.get("ads:duplicate_windows") or 0)
    except Exception as e:  # noqa: BLE001
        print(f"[report] Redis not reachable ({e}); skipping freshness")
        return None
    if len(vals) == 0:
        return {"samples": 0, "late_events": late, "malformed_events": bad, "duplicate_windows": dup}
    p = np.percentile(vals, [50, 95, 99])
    return {"samples": int(len(vals)), "p50_ms": float(p[0]), "p95_ms": float(p[1]), "p99_ms": float(p[2]),
            "late_events": late, "malformed_events": bad, "duplicate_windows": dup}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results/ads")
    ap.add_argument("--redis-host", default="localhost")
    ap.add_argument("--redis-port", type=int, default=6379)
    ap.add_argument("--window-ms", type=int, default=5000)
    ap.add_argument("--out", default="results/RESULTS_ads.md")
    a = ap.parse_args()
    res = Path(a.results)
    sim = json.loads((res / "sim.json").read_text()) if (res / "sim.json").exists() else None
    k6 = json.loads((res / "k6_auction.json").read_text()) if (res / "k6_auction.json").exists() else None
    fr = freshness(a.redis_host, a.redis_port)
    if fr is not None:
        (res / "freshness.json").write_text(json.dumps(fr, indent=2))

    rows = []
    if k6:
        l = k6["latency_ms"]
        rows += [
            ("Auction throughput (k6 %s, %s VUs, %s)" % (k6.get("runner", ""), k6["vus"], k6["duration"]), f"**{k6['req_per_s']:,.0f} req/s**, {k6['failed_rate']:.2%} failed"),
            ("Auction latency p50 / p95 / p99", f"**{l['p50']:.2f} / {l['p95']:.2f} / {l['p99']:.2f} ms**"),
        ]
    if fr and fr.get("samples"):
        rows += [
            (f"Event -> Redis CTR freshness ({a.window_ms // 1000} s windows)", f"p50 {fr['p50_ms'] / 1000:.1f} s, p95 {fr['p95_ms'] / 1000:.1f} s, p99 {fr['p99_ms'] / 1000:.1f} s ({fr['samples']:,} windows)"),
            ("Late / malformed events, re-emitted windows", f"{fr['late_events']:,} / {fr['malformed_events']:,} / {fr['duplicate_windows']:,}"),
        ]
    if sim:
        f, l = sim["first_10pct"], sim["last_10pct"]
        t = sim["server_totals"]
        rows += [
            ("Click sim requests (%s users)" % ("synthetic" if sim["inputs_source"] == "synthetic" else "real OLX"),
             f"{sim['requests']:,} at {sim['sim_req_per_s']:,.0f} req/s, {sim['http_errors']} errors"),
            ("Impressions / clicks / charged clicks", f"{t['impressions']:,} / {t['clicks']:,} / {t['charged_clicks']:,}"),
            ("Flink CTR vs expected CTR, mean abs error", f"{sim['flink_ctr_mae_vs_expected']:.4f} (expected mean {sim['expected_ctr_mean']:.4f}, {sim['ads_judged']} ads with >=200 impressions)"),
            ("pCTR vs hidden CTR, Spearman", f"**{sim['spearman_pctr_vs_hidden_ctr']:.3f}**"),
            ("Impressions to top-quartile ads, first vs last 10%", f"**{f['best_ad_share']:.1%} -> {l['best_ad_share']:.1%}** (random would be {sim['random_best_share']:.0%})"),
            ("Sponsored CTR, first vs last 10%", f"{f['ctr']:.2%} -> {l['ctr']:.2%}"),
            ("Budget-filtered candidates / blender-rejected winners", f"{t['budget_filtered_candidates']:,} / {t['blender_rejected_winners']:,}"),
        ]
    lines = ["# Sponsored jobs (ads) results", "",
             "Generated by `ads/sim/report.py` from `results/ads/`. Clicks are simulated (hidden per-ad CTR, see ads/README.md); users, jobs and organic candidates are real OLX data unless the source below says synthetic.",
             "", f"Inputs: `{sim['inputs_source'] if sim else 'n/a'}`", "", "| What | Number |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in rows]
    Path(a.out).write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
