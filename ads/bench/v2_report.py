"""Everything the v2 benchmarks wrote -> results/RESULTS_ads_v2.md. Missing pieces say "not run yet"."""
from __future__ import annotations

import glob
import json
import os
from collections import Counter

R = "results"


def load(path: str):
    try:
        return json.load(open(path))
    except (OSError, ValueError):
        return None


def k6_row(label: str, d: dict) -> str:
    l = d["latency_ms"]
    return (f"| {label} | {d['vus']} | {d['req_per_s']:,.0f} | {l['p50']:.2f} | {l['p95']:.2f} | {l['p99']:.2f} | "
            f"{d['failed_rate'] * 100:.2f}% |")


def main() -> None:
    md = ["# PathRank ads v2 results", "",
          "Generated by `ads/bench/v2_report.py` from `results/ads*/`. All runs on one machine "
          "(see each section for the setup). Simulated clicks, real OLX users and jobs.", ""]

    md += ["## Platform threads vs Java 21 virtual threads, auth off vs on (`ads/bench/compare.sh`)", ""]
    runs = sorted(glob.glob(f"{R}/ads/compare/*.json"))
    if runs:
        md += ["| run | VUs | req/s | p50 ms | p95 ms | p99 ms | failed |", "|---|---|---|---|---|---|---|"]
        for p in runs:
            md.append(k6_row(os.path.basename(p)[:-5], load(p)))
    else:
        md.append("_not run yet: `make ads-compare`_")
    md.append("")

    md += ["## Redis vs Valkey as the CTR cache (`CACHE=valkey make ads-bench`)", ""]
    pairs = [("Redis 7", f"{R}/ads"), ("Valkey 8", f"{R}/ads_valkey")]
    if all(load(f"{d}/k6_auction.json") for _, d in pairs):
        md += ["| cache | VUs | req/s | p50 ms | p95 ms | p99 ms | failed |", "|---|---|---|---|---|---|---|"]
        for name, d in pairs:
            md.append(k6_row(name, load(f"{d}/k6_auction.json")))
        for name, d in pairs:
            f = load(f"{d}/freshness.json")
            if f:
                md.append(f"\n{name} event -> cache freshness: `{json.dumps(f)}`")
    else:
        md.append("_not run yet: `make ads-bench` and `CACHE=valkey make ads-bench`_")
    md.append("")

    md += ["## Shared budget across two ad server processes (`ads/bench/overspend.py`)", ""]
    rows = [load(f"{R}/ads/overspend_{db}.json") for db in ("postgres", "cockroach")]
    if any(rows):
        md += ["| database | attempts | fit budget | charged | overspend | retries | charges/s | p50 / p99 ms |",
               "|---|---|---|---|---|---|---|---|"]
        for o in rows:
            if o:
                md.append(f"| {o['db']} | {o['attempts']:,} | {o['clicks_that_fit_budget']:,} | {o['charged']:,} | "
                          f"{o['overspend_micros']} micros | {o['retries']:,} | {o['charges_per_s']:,.0f} | "
                          f"{o['latency_ms']['p50']} / {o['latency_ms']['p99']} |")
    else:
        md.append("_not run yet: `make ads-overspend`_")
    md.append("")

    md += ["## Authorization probe against the live secured server (`ads/bench/security_probe.py`)", ""]
    s = load(f"{R}/ads/security.json")
    if s:
        md.append(f"Rejected **{s['rejected_correctly']}/{s['unauthorized_requests']}** unauthorized requests with the "
                  f"right status; **{s['allowed_ok']}/{s['allowed_requests']}** legitimate requests succeeded.")
        md += ["", "| category | correct | wrong |", "|---|---|---|"]
        for k, v in s["by_category"].items():
            md.append(f"| {k} | {v.get('ok', 0)} | {v.get('wrong', 0)} |")
    else:
        md.append("_not run yet: `make ads-compare` runs it_")
    md.append("")

    md += ["## Console (`ads/console`)", ""]
    pw = load(f"{R}/ads/playwright.json")
    if pw:
        by = Counter()
        def walk(suite):
            for sp in suite.get("specs", []):
                for t in sp.get("tests", []):
                    status = t["results"][-1]["status"] if t.get("results") else "skipped"
                    by[(t["projectName"], status)] += 1
            for ch in suite.get("suites", []):
                walk(ch)
        for suite in pw.get("suites", []):
            walk(suite)
        projects = sorted({p for p, _ in by})
        md += ["| Playwright project | passed | failed |", "|---|---|---|"]
        for p in projects:
            md.append(f"| {p} | {by[(p, 'passed')]} | {by[(p, 'failed')] + by[(p, 'timedOut')]} |")
    else:
        md.append("_Playwright not run yet: `make ads-console-e2e`_")
    lh = load(f"{R}/ads/lighthouse.json")
    md.append("")
    md.append(f"Lighthouse ({lh['formFactor']}): `{json.dumps(lh['scores'])}`, LCP {lh['lcp_ms']} ms" if lh
              else "_Lighthouse not run yet: `make ads-console-lighthouse`_")
    md.append("")

    os.makedirs(R, exist_ok=True)
    open(f"{R}/RESULTS_ads_v2.md", "w").write("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
